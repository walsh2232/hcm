#!/usr/bin/env python3
"""Build/search a separate SQLite FTS5 index across private Oracle PDF/HTML corpora.

Input is generated by ingest_pdf.py or ingest_oracle_html.py. Outputs default
to .local/oracle-search/external-index.sqlite and are git-ignored.
"""
from __future__ import annotations
import argparse
import json
import sqlite3
from pathlib import Path


def collect_rows(root: Path):
    inputs = sorted(root.rglob("retrieval-chunks.jsonl"))
    rows = []
    for path in inputs:
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            try:
                item = json.loads(line)
            except Exception as exc:
                raise SystemExit(f"Invalid JSON in {path}:{n}: {exc}")
            pdf_start, pdf_end = item.get("source_pdf_page_start"), item.get("source_pdf_page_end")
            html_start, html_end = item.get("source_html_sequence_start"), item.get("source_html_sequence_end")
            kind = item.get("source_kind") or ("pdf" if pdf_start is not None or pdf_end is not None else ("oracle-help-center-html" if html_start is not None or html_end is not None else "unknown"))
            rows.append((
                item.get("chunk_id"), item.get("doc_id"), item.get("title"), item.get("edition"),
                kind, pdf_start, pdf_end, html_start, html_end, item.get("canonical_url"),
                item.get("source_url_start"), item.get("source_url_end"), str(path), item.get("text", "")
            ))
    return inputs, rows


def build(root: Path, database: Path):
    inputs, rows = collect_rows(root)
    if not inputs:
        raise SystemExit(f"No retrieval-chunks.jsonl files found under {root}. Ingest a PDF or Oracle HTML guide first.")
    database.parent.mkdir(parents=True, exist_ok=True)
    if database.exists():
        database.unlink()
    conn = sqlite3.connect(database)
    conn.execute("CREATE VIRTUAL TABLE chunk_fts USING fts5(chunk_id UNINDEXED, doc_id UNINDEXED, title, edition UNINDEXED, source_kind UNINDEXED, pdf_start UNINDEXED, pdf_end UNINDEXED, html_start UNINDEXED, html_end UNINDEXED, canonical_url UNINDEXED, source_url_start UNINDEXED, source_url_end UNINDEXED, chunk_file UNINDEXED, body, tokenize='unicode61 remove_diacritics 2')")
    conn.executemany("INSERT INTO chunk_fts VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)", rows)
    conn.commit()
    integrity = conn.execute("PRAGMA integrity_check").fetchone()[0]
    by_kind = conn.execute("SELECT source_kind,COUNT(*) FROM chunk_fts GROUP BY source_kind").fetchall()
    conn.close()
    print(json.dumps({"database":str(database),"chunk_files":len(inputs),"chunks":len(rows),"by_source_kind":dict(by_kind),"integrity":integrity},indent=2))


def search(database: Path, query: str, limit: int, as_json: bool):
    if not database.exists():
        raise SystemExit(f"Search index not found: {database}. Run build first.")
    conn = sqlite3.connect(database)
    conn.row_factory = sqlite3.Row
    sql = "SELECT chunk_id,doc_id,title,edition,source_kind,pdf_start,pdf_end,html_start,html_end,canonical_url,source_url_start,source_url_end,snippet(chunk_fts,13,'[',']',' … ',25) AS excerpt,bm25(chunk_fts) AS score FROM chunk_fts WHERE chunk_fts MATCH ? ORDER BY score LIMIT ?"
    try:
        try:
            found = conn.execute(sql, (query, limit)).fetchall()
        except sqlite3.OperationalError:
            terms = [w.strip('"') for w in query.split() if w.strip('"')]
            fallback = " OR ".join('"' + w.replace('"', '') + '"' for w in terms)
            found = conn.execute(sql, (fallback, limit)).fetchall()
        items = [dict(row) for row in found]
    finally:
        conn.close()
    if as_json:
        print(json.dumps(items, indent=2, ensure_ascii=False))
        return
    if not items:
        print("No results. Try fewer or different keywords.")
        return
    for i, row in enumerate(items, 1):
        if row["source_kind"] == "oracle-help-center-html":
            location = f"Oracle HTML sequence {row['html_start'] or '?'}–{row['html_end'] or '?'}"
        else:
            location = f"PDF pp. {row['pdf_start'] or '?'}–{row['pdf_end'] or '?'}"
        url = row["source_url_start"] or row["canonical_url"]
        print(f"{i}. {row['title']} ({row['doc_id']}, {row['edition'] or 'edition unknown'}) — {location}")
        if url:
            print(f"   Source: {url}")
        print(f"   Chunk: {row['chunk_id']} · {row['excerpt']}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["build","search"])
    parser.add_argument("query", nargs="?", default="")
    parser.add_argument("--root", type=Path, default=Path.cwd()/".local"/"oracle-docs")
    parser.add_argument("--database", type=Path, default=Path.cwd()/".local"/"oracle-search"/"external-index.sqlite")
    parser.add_argument("--limit", type=int, default=8)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    if args.command == "build":
        build(args.root.resolve(), args.database.resolve())
    else:
        if not args.query.strip():
            parser.error("search requires a query")
        search(args.database.resolve(), args.query, args.limit, args.json)


if __name__ == "__main__":
    main()
